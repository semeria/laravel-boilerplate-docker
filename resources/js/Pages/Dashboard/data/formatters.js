const currencyFormatter = new Intl.NumberFormat('es-MX', {
    style: 'currency',
    currency: 'MXN',
    maximumFractionDigits: 0,
});

export const formatCurrency = (amount) => currencyFormatter.format(amount);

const transactionCurrencyFormatter = new Intl.NumberFormat('es-MX', {
    style: 'currency',
    currency: 'MXN',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
});

export const formatTransactionCurrency = (amount) => transactionCurrencyFormatter.format(amount);
